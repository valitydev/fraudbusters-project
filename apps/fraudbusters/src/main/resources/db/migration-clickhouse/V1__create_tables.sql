CREATE DATABASE IF NOT EXISTS fraud ON CLUSTER '{cluster}';

CREATE TABLE IF NOT EXISTS fraud.events_unique ON CLUSTER '{cluster}' (
    timestamp Date,
    eventTimeHour UInt64,
    eventTime UInt64,
    payerType String,
    tokenProvider String,
    partyId String,
    shopId String,
    ip String,
    email String,
    bin String,
    fingerprint String,
    resultStatus String,
    amount UInt64,
    country String,
    checkedRule String,
    bankCountry String,
    currency String,
    invoiceId String,
    lastDigits String,
    bankName String,
    cardToken String,
    paymentId String,
    mobile UInt8,
    recurrent UInt8,
    checkedTemplate String,
    id String,
    customerId Nullable(String),
    userId Nullable(String)
) ENGINE = ReplicatedMergeTree('/clickhouse/{cluster}/tables/{shard}/fraud/events_unique', '{replica}')
PARTITION BY toYYYYMM(timestamp)
ORDER BY (eventTimeHour, partyId, shopId, bin, resultStatus, cardToken, email, ip, fingerprint)
TTL timestamp + toIntervalMonth(3);

