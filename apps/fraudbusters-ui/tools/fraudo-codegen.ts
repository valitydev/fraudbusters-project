/**
 * Builds the Fraudo vocabulary used by the rule editor: function names (`'name' LPAREN`)
 * and the `result` / `catch_result` alternatives from the ANTLR grammar of
 * packages/libs/fraudo, and the field names that fraudbusters resolves for payments and
 * payouts (PaymentCheckedField / PayoutCheckedField). Run `npm run fraudo-codegen` after
 * the grammar or those enums change.
 */
import * as fs from 'fs';
import * as path from 'path';

// Prettier 2 ships without typings; only the synchronous API is used here.
// eslint-disable-next-line @typescript-eslint/no-var-requires
const prettier: {
    format(source: string, options: object): string;
    resolveConfig: { sync(file: string): object | null };
} = require('prettier');

const GRAMMAR_DIR = path.resolve(__dirname, '../../../packages/libs/fraudo/src/main/antlr4/imports');
const FIELDS_DIR = path.resolve(__dirname, '../../fraudbusters/src/main/java/dev/vality/fraudbusters/fraud/constant');
const OUTPUT = path.resolve(__dirname, '../src/app/shared/pipes/fraudo-grammar.generated.ts');

function literals(source: string, pattern: RegExp): string[] {
    const found: string[] = [];
    let match: RegExpExecArray | null;
    while ((match = pattern.exec(source))) {
        found.push(match[1]);
    }
    return found;
}

function ruleAlternatives(source: string, rule: string): string[] {
    const body = new RegExp(`^${rule}\\s*\\n\\s*:([^;]*);`, 'm').exec(source);
    if (!body) {
        throw new Error(`Rule "${rule}" not found in the Fraudo grammar`);
    }
    return literals(body[1], /'([^']+)'/g);
}

function list(name: string, values: string[]): string {
    const items = Array.from(new Set(values))
        .sort()
        .map((value) => `    '${value}',`)
        .join('\n');
    return `export const ${name}: ReadonlySet<string> = new Set([\n${items}\n]);\n`;
}

const files = fs
    .readdirSync(GRAMMAR_DIR)
    .filter((file) => file.endsWith('.g4'))
    .sort();
const sources = files.map((file) => fs.readFileSync(path.join(GRAMMAR_DIR, file), 'utf8'));
const common = sources[files.indexOf('FraudoCommon.g4')];

const functions = sources.reduce<string[]>(
    (names, source) => names.concat(literals(source, /'([A-Za-z_]\w*)'\s+LPAREN/g)),
    []
);

function enumValues(file: string): string[] {
    const values = literals(fs.readFileSync(path.join(FIELDS_DIR, file), 'utf8'), /^\s*[A-Z_]+\("([^"]+)"\)[,;]/gm);
    if (!values.length) {
        throw new Error(`No fields found in ${file}`);
    }
    return values;
}

const output = [
    `// Generated by tools/fraudo-codegen.ts from ${files.join(', ')}, PaymentCheckedField.java`,
    '// and PayoutCheckedField.java. Do not edit.',
    '',
    '/** Every function of the Fraudo grammar, payments and payouts alike. */',
    list('FRAUDO_FUNCTIONS', functions),
    '/** Results allowed after `->`. */',
    list('FRAUDO_RESULTS', ruleAlternatives(common, 'result')),
    '/** Results allowed after `catch:`. */',
    list('FRAUDO_CATCH_RESULTS', ruleAlternatives(common, 'catch_result')),
    '/** Fields of payment rules (fraudbusters PaymentCheckedField). */',
    list('FRAUDO_PAYMENT_FIELDS', enumValues('PaymentCheckedField.java')),
    '/** Fields of payout rules (fraudbusters PayoutCheckedField). */',
    list('FRAUDO_PAYOUT_FIELDS', enumValues('PayoutCheckedField.java')),
].join('\n');

// Format with the project's Prettier config, so CI can regenerate the file and still pass `ui:check`.
fs.writeFileSync(OUTPUT, prettier.format(output, { ...prettier.resolveConfig.sync(OUTPUT), filepath: OUTPUT }));
console.log(
    `Fraudo vocabulary: ${new Set(functions).size} functions written to ${path.relative(process.cwd(), OUTPUT)}`
);
